//! The TypeScript bindings in `apps/desktop/src/api/generated` (E0-13
//! D-row "types"): one ts-rs file per record, and `commands.ts`, a typed
//! wrapper for every command built from the manifest (`ipc::commands!`).
//!
//! The files are committed. `bindings_are_current` fails when they differ
//! from what the Rust side generates; regenerate with
//! `DW_UPDATE_BINDINGS=1 cargo test -p dw-app bindings`.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use ts_rs::{Config, TS};

use crate::bridge::{AppEvent, EVENT, MAX_TXIDS};
use crate::error::{AppError, ErrorCode};
use crate::ipc::{Exports, Imports, TypeSpec};

/// The generated directory, from this crate's manifest directory.
pub fn generated_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../apps/desktop/src/api/generated")
}

fn config(dir: &Path) -> Config {
    // Duff amounts and UNIX times fit a JSON number exactly (< 2^53); credit
    // amounts, which may not, are strings (`dto::credits`).
    Config::new().with_out_dir(dir).with_large_int("number")
}

/// Writes every binding into `dir`.
pub fn write_bindings(dir: &Path) -> Result<(), String> {
    let cfg = config(dir);
    let mut exports = Exports::default();
    let specs = crate::api::specs();
    let types = specs
        .iter()
        .flat_map(|(_, s)| s.args.iter().map(|(_, t)| *t).chain([s.ret]))
        .chain([TypeSpec::of::<AppEvent>(), TypeSpec::of::<AppError>()]);
    for t in types {
        t.export(&cfg, &mut exports)?;
    }
    // Re-exported for the renderer's error handling; written with `AppError`.
    if let Some(path) = ErrorCode::output_path() {
        exports.imports.insert(ErrorCode::ident(&cfg), path);
    }
    let ts = commands_ts(&cfg, &exports.imports);
    std::fs::write(dir.join("commands.ts"), ts).map_err(|e| e.to_string())
}

/// `snake_case` → `camelCase`, as Tauri renames command arguments.
pub fn camel(snake: &str) -> String {
    let mut out = String::with_capacity(snake.len());
    let mut upper = false;
    for c in snake.chars() {
        if c == '_' {
            upper = true;
        } else if upper {
            out.extend(c.to_uppercase());
            upper = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn commands_ts(cfg: &Config, imports: &Imports) -> String {
    let specs = crate::api::specs();
    let mut ts = String::from(
        "// Generated by dw-app (`DW_UPDATE_BINDINGS=1 cargo test -p dw-app bindings`). Do not edit.\n\
         // Every command rejects with `AppError`.\n\
         import { invoke } from \"@tauri-apps/api/core\";\n",
    );
    for (name, path) in imports {
        let module = path.with_extension("");
        let _ = writeln!(
            ts,
            "import type {{ {name} }} from \"./{}\";",
            module.display()
        );
    }
    let _ = writeln!(
        ts,
        "\nexport type {{ AppError, AppEvent, ErrorCode }};\n\n\
         /** The Tauri event every engine event is sent on, with an `AppEvent` payload. */\n\
         export const ENGINE_EVENT = {EVENT:?};\n\n\
         /** Txids per `historyChanged` or `newTransactions` event. */\n\
         export const MAX_TXIDS = {MAX_TXIDS};"
    );
    for (_, spec) in &specs {
        let args: Vec<(String, String)> = spec
            .args
            .iter()
            .map(|(n, t)| (camel(n), t.ts_name(cfg)))
            .collect();
        // Every argument is written out, `null` included: a left-out
        // passphrase or label must not mean "none" by accident.
        let params: Vec<String> = args.iter().map(|(n, t)| format!("{n}: {t}")).collect();
        let fields: Vec<String> = args.iter().map(|(n, _)| n.clone()).collect();
        ts.push('\n');
        let docs: Vec<&str> = spec
            .docs
            .iter()
            .map(|l| l.strip_prefix(' ').unwrap_or(l))
            .collect();
        if !docs.is_empty() {
            ts.push_str("/**\n");
            for line in docs {
                let _ = writeln!(
                    ts,
                    " *{}{}",
                    if line.is_empty() { "" } else { " " },
                    line.replace("*/", "*\\/")
                );
            }
            ts.push_str(" */\n");
        }
        let ret = spec.ret.ts_name(cfg);
        let _ = writeln!(
            ts,
            "export function {}({}): Promise<{ret}> {{\n  return invoke<{ret}>({:?}{});\n}}",
            camel(spec.name),
            params.join(", "),
            spec.name,
            if fields.is_empty() {
                String::new()
            } else {
                format!(", {{ {} }}", fields.join(", "))
            }
        );
    }
    ts.push_str(
        "\n/** Each command's arguments, as `invoke` sends them. */\nexport type CommandArgs = {\n",
    );
    for (_, spec) in &specs {
        let fields: Vec<String> = spec
            .args
            .iter()
            .map(|(n, t)| format!("{}: {}", camel(n), t.ts_name(cfg)))
            .collect();
        let _ = writeln!(ts, "  {}: {{ {} }};", spec.name, fields.join("; "));
    }
    ts.push_str("};\n\n/** Each command's result. */\nexport type CommandResults = {\n");
    for (_, spec) in &specs {
        let _ = writeln!(ts, "  {}: {};", spec.name, spec.ret.ts_name(cfg));
    }
    ts.push_str("};\n\nexport type CommandName = keyof CommandResults;\n\n/** Every command, with the `api/` module that declares it. */\nexport const COMMANDS: Record<CommandName, string> = {\n");
    for (domain, spec) in &specs {
        let _ = writeln!(ts, "  {}: {domain:?},", spec.name);
    }
    ts.push_str(
        "};\n\n/** Every error code. */\nexport const ERROR_CODES: readonly ErrorCode[] = [\n",
    );
    for code in ErrorCode::all() {
        let _ = writeln!(ts, "  {:?},", code.as_str());
    }
    ts.push_str("];\n");
    ts
}

#[cfg(test)]
pub(crate) mod tests {
    use super::*;

    /// Every file under `dir`, by path relative to it.
    pub(crate) fn read_dir_sorted(dir: &Path) -> Vec<(PathBuf, String)> {
        fn walk(root: &Path, dir: &Path, out: &mut Vec<(PathBuf, String)>) {
            for e in std::fs::read_dir(dir).into_iter().flatten().flatten() {
                let path = e.path();
                if path.is_dir() {
                    walk(root, &path, out);
                } else {
                    let rel = path.strip_prefix(root).unwrap_or(&path).to_path_buf();
                    out.push((rel, std::fs::read_to_string(&path).unwrap_or_default()));
                }
            }
        }
        let mut files = Vec::new();
        walk(dir, dir, &mut files);
        files.sort();
        files
    }

    pub(crate) fn update() -> bool {
        std::env::var_os("DW_UPDATE_BINDINGS").is_some()
    }

    /// The committed bindings equal what the Rust side generates.
    #[test]
    fn bindings_are_current() {
        let fresh = tempfile::tempdir().unwrap();
        write_bindings(fresh.path()).unwrap();
        let committed = generated_dir();
        if update() {
            let _ = std::fs::remove_dir_all(&committed);
            std::fs::create_dir_all(&committed).unwrap();
            for (name, text) in read_dir_sorted(fresh.path()) {
                let path = committed.join(name);
                std::fs::create_dir_all(path.parent().unwrap()).unwrap();
                std::fs::write(path, text).unwrap();
            }
        }
        assert_eq!(
            read_dir_sorted(&committed),
            read_dir_sorted(fresh.path()),
            "apps/desktop/src/api/generated is stale; run DW_UPDATE_BINDINGS=1 cargo test -p dw-app bindings"
        );
    }

    /// Two Rust types of one TypeScript name are refused, not overwritten.
    #[test]
    fn a_type_name_clash_is_refused() {
        #[allow(dead_code)]
        mod a {
            #[derive(ts_rs::TS)]
            pub struct Clash {
                pub x: u8,
            }
        }
        #[allow(dead_code)]
        mod b {
            #[derive(ts_rs::TS)]
            pub struct Clash {
                pub y: String,
            }
            #[derive(ts_rs::TS)]
            pub struct Holder {
                pub inner: Option<Clash>,
            }
        }
        let dir = tempfile::tempdir().unwrap();
        let cfg = config(dir.path());
        let mut exports = Exports::default();
        TypeSpec::of::<a::Clash>()
            .export(&cfg, &mut exports)
            .unwrap();
        // The same type again is fine.
        TypeSpec::of::<a::Clash>()
            .export(&cfg, &mut exports)
            .unwrap();
        // Reached as a dependency, not only at the signature's level.
        let e = TypeSpec::of::<b::Holder>()
            .export(&cfg, &mut exports)
            .unwrap_err();
        assert!(e.contains("Clash.ts"), "{e}");
    }

    #[test]
    fn argument_names_are_camel_case() {
        assert_eq!(camel("wallet_id"), "walletId");
        assert_eq!(camel("initial_protocol_version"), "initialProtocolVersion");
        assert_eq!(camel("lock"), "lock");
    }
}
