export function birthHeightFor(date: Date, network: NetworkInfo["kind"]): number {
  const cutoff = date.getTime() / 1000 - SAFETY_MARGIN_SECS;
  let height = 0;
  for (const [h, time] of ANCHORS[network] ?? []) {
    if (time > cutoff) break;
    height = h;
  }
  return height;
}
